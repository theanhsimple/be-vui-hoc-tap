// Generates out/sw.js for the DEVICE edition after `next build`:
// precaches every page (HTML) and static asset so the app works offline
// once opened (HTML, static assets and the RSC payloads used by client-side
// navigation, *.txt).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

const walk = (d) =>
  readdirSync(d).flatMap((f) => {
    const p = join(d, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

const files = walk(OUT)
  .map((p) => relative(OUT, p).split(sep).join("/"))
  .filter((f) => f !== "sw.js" && !f.endsWith(".map"));

const urls = files.map((f) =>
  f === "index.html"
    ? `${base}/`
    : f.endsWith("/index.html")
      ? `${base}/${f.slice(0, -"index.html".length)}`
      : `${base}/${f}`,
);

const hash = createHash("sha256");
for (const f of files.sort()) hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);

const sw = `// GENERATED by scripts/build-sw.mjs — offline support for the device edition.
const VERSION = "little-${version}";
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(VERSION).then(async (cache) => {
      // One by one so a single failure does not stop the rest.
      for (const url of PRECACHE) {
        try { await cache.add(new Request(url, { cache: "reload" })); } catch {}
      }
    }).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("little-") && k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

async function networkFirst(request) {
  const cache = await caches.open(VERSION);
  try {
    const response = await fetch(request);
    if (response.ok) cache.put(request, response.clone());
    return response;
  } catch {
    const hit = (await cache.match(request, { ignoreSearch: true })) ??
      (await cache.match(BASE + "/student/welcome/"));
    if (hit) return hit;
    throw new Error("offline");
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(VERSION);
  const hit = await cache.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + "/")) return;
  if (url.pathname.includes("/_next/static/") || url.pathname.includes("/icons/")) {
    event.respondWith(cacheFirst(request));
  } else {
    // Pages and RSC payloads: fresh when online, cached when offline.
    event.respondWith(networkFirst(request));
  }
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
