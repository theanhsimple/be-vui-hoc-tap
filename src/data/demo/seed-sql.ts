import "server-only";

import { LEARNING_WORLDS } from "@/design-system/worlds";
import type { AnswerKey } from "@/features/learning/grading/keys";
import { REWARDS } from "@/features/learning/progress/rewards";
import type { LearningQuestion } from "@/features/learning/types";

import { DEMO_ANSWER_KEYS } from "./answer-keys";
import type { WorldSource } from "./helpers";
import { DEMO_WORLD_SOURCES } from "./index";
import { PLACEMENT_ASSESSMENT, SKILL_GUIDES } from "./parent-guides";
import { REWARD_RULES } from "./reward-rules";

/**
 * Generates supabase/seed.sql from the Sprint 03 demo library, so the
 * database content and the reviewed TypeScript source can never drift
 * (checked by seed.test.ts; regenerate with `pnpm db:seed:generate`).
 *
 * The seed is DEVELOPMENT / STAGING data: it publishes the demo library.
 * It is idempotent (upserts on stable slugs) and never deletes rows.
 */

const lit = (s: string) => `'${s.replaceAll("'", "''")}'`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const nullable = (v: unknown) => (v === undefined ? "null" : json(v));
const num = (n: number) => String(n);

const DIFFICULTY = { L1: 1, L2: 2, L3: 3, L4: 4 } as const;

/** Public config column for a question (no correctness information). */
export function publicConfig(q: LearningQuestion): Record<string, unknown> {
  switch (q.type) {
    case "single_choice":
      return { options: q.options, confirm: q.config.confirm };
    case "image_choice":
      return { options: q.options };
    default:
      return q.config;
  }
}

/** Private key JSON as stored in private.question_answer_keys.answer. */
export function privateAnswer(
  q: LearningQuestion,
  key: AnswerKey,
): Record<string, unknown> {
  if (key.type === "memory") {
    if (q.type !== "memory") throw new Error(`${q.id}: memory key mismatch`);
    const groups = new Map<string, string[]>();
    for (const c of q.config.cards) {
      groups.set(c.pairKey, [...(groups.get(c.pairKey) ?? []), c.id]);
    }
    return {
      type: "memory",
      pairs: [...groups.values()].map((ids) => {
        if (ids.length !== 2) throw new Error(`${q.id}: card without a pair`);
        return ids;
      }),
    };
  }
  if (key.type === "choice") return { type: "choice", optionId: key.optionId };
  return key;
}

export interface SeedStats {
  modules: number;
  skills: number;
  lessons: number;
  questions: number;
  keys: number;
  rewards: number;
}

export function seedStats(
  sources: readonly WorldSource[] = DEMO_WORLD_SOURCES,
): SeedStats {
  const skills = sources.flatMap((w) => w.skills);
  const lessons = skills.flatMap((s) => s.lessons);
  const questions = lessons.flatMap((l) => l.questions);
  return {
    modules: sources.length,
    skills: skills.length,
    lessons: lessons.length,
    questions: questions.length,
    keys: questions.filter((q) => DEMO_ANSWER_KEYS[q.id]).length,
    rewards: REWARDS.length,
  };
}

export function buildSeedSql(
  sources: readonly WorldSource[] = DEMO_WORLD_SOURCES,
): string {
  const out: string[] = [];
  const stats = seedStats(sources);
  out.push(
    "-- GENERATED by src/data/demo/seed-sql.ts — do not edit by hand.",
    "-- Regenerate: pnpm db:seed:generate. Development/staging data only:",
    "-- publishes the Sprint 03 DEMO library (not official curriculum, not",
    "-- entrance-exam material). Idempotent: upserts on slugs, never deletes.",
    "",
    "begin;",
    "",
  );

  sources.forEach((w, wi) => {
    const meta = LEARNING_WORLDS.find((m) => m.id === w.id);
    if (!meta) throw new Error(`Unknown world ${w.id}`);
    out.push(
      `-- ${meta.nameEn}`,
      `insert into public.modules (slug, title_vi, title_en, category, description, tone, illustration, sort_order, unlock_min_completed_lessons, status, published_at)`,
      `values (${lit(w.id)}, ${lit(meta.nameVi)}, ${lit(meta.nameEn)}, ${lit(w.category)}, ${lit(w.description)}, ${lit(meta.tone)}, ${lit(meta.illustration)}, ${num((wi + 1) * 10)}, ${w.unlock ? num(w.unlock.minCompletedLessons) : "null"}, 'published', now())`,
      `on conflict (slug) do update set title_vi = excluded.title_vi, title_en = excluded.title_en, category = excluded.category, description = excluded.description, tone = excluded.tone, illustration = excluded.illustration, sort_order = excluded.sort_order, unlock_min_completed_lessons = excluded.unlock_min_completed_lessons;`,
    );
    w.skills.forEach((s, si) => {
      const guide = SKILL_GUIDES[s.id];
      if (!guide) throw new Error(`Missing parent guide for ${s.id}`);
      out.push(
        `insert into public.skills (module_id, slug, title_vi, sort_order, parent_summary_vi, home_activity_vi, status, published_at)`,
        `values ((select id from public.modules where slug = ${lit(w.id)}), ${lit(s.id)}, ${lit(s.title)}, ${num((si + 1) * 10)}, ${lit(guide.summary)}, ${lit(guide.homeActivity)}, 'published', now())`,
        `on conflict (slug) do update set title_vi = excluded.title_vi, sort_order = excluded.sort_order, parent_summary_vi = excluded.parent_summary_vi, home_activity_vi = excluded.home_activity_vi;`,
      );
      s.lessons.forEach((l, li) => {
        out.push(
          `insert into public.lessons (skill_id, slug, title_vi, objective_vi, minutes, cover, sort_order, status, published_at)`,
          `values ((select id from public.skills where slug = ${lit(s.id)}), ${lit(l.id)}, ${lit(l.title)}, ${lit(l.objective)}, ${num(l.minutes)}, ${json(l.cover)}, ${num((li + 1) * 10)}, 'published', now())`,
          `on conflict (slug) do update set title_vi = excluded.title_vi, objective_vi = excluded.objective_vi, minutes = excluded.minutes, cover = excluded.cover, sort_order = excluded.sort_order;`,
        );
        l.questions.forEach((q, qi) => {
          const key = DEMO_ANSWER_KEYS[q.id];
          if (!key) throw new Error(`Missing answer key for ${q.id}`);
          const qid = `(select id from public.questions where slug = ${lit(q.id)})`;
          out.push(
            `insert into public.questions (slug, skill_id, type, difficulty, prompt_vi, instruction_audio_url, stimulus, memorize, feedback, config, max_attempts, status, published_at)`,
            `values (${lit(q.id)}, (select id from public.skills where slug = ${lit(s.id)}), ${lit(q.type)}, ${num(DIFFICULTY[q.difficulty])}, ${lit(q.prompt)}, ${q.instructionAudioUrl ? lit(q.instructionAudioUrl) : "null"}, ${nullable(q.stimulus)}, ${nullable(q.memorize)}, ${nullable(q.feedback)}, ${json(publicConfig(q))}, ${num(q.maxAttempts ?? 2)}, 'published', now())`,
            `on conflict (slug) do update set skill_id = excluded.skill_id, type = excluded.type, difficulty = excluded.difficulty, prompt_vi = excluded.prompt_vi, instruction_audio_url = excluded.instruction_audio_url, stimulus = excluded.stimulus, memorize = excluded.memorize, feedback = excluded.feedback, config = excluded.config, max_attempts = excluded.max_attempts;`,
            `insert into private.question_answer_keys (question_id, answer, hint_eliminate)`,
            `values (${qid}, ${json(privateAnswer(q, key))}, ${key.type === "choice" && key.hintEliminate ? lit(key.hintEliminate) : "null"})`,
            `on conflict (question_id) do update set answer = excluded.answer, hint_eliminate = excluded.hint_eliminate;`,
            `insert into public.lesson_questions (lesson_id, question_id, position)`,
            `values ((select id from public.lessons where slug = ${lit(l.id)}), ${qid}, ${num(qi + 1)})`,
            `on conflict (lesson_id, position) do update set question_id = excluded.question_id;`,
          );
        });
      });
    });
    out.push("");
  });

  out.push("-- Rewards");
  REWARDS.forEach((r, i) => {
    const rule = REWARD_RULES[r.id];
    if (!rule) throw new Error(`Missing reward rule for ${r.id}`);
    out.push(
      `insert into public.rewards (key, kind, title_vi, title_en, criteria_vi, illustration, rule, sort_order, status, published_at)`,
      `values (${lit(r.id)}, 'badge', ${lit(r.name)}, ${lit(r.nameEn)}, ${lit(r.criteria)}, ${lit(r.illustration)}, ${json(rule)}, ${num((i + 1) * 10)}, 'published', now())`,
      `on conflict (key) do update set title_vi = excluded.title_vi, title_en = excluded.title_en, criteria_vi = excluded.criteria_vi, illustration = excluded.illustration, rule = excluded.rule, sort_order = excluded.sort_order;`,
    );
  });

  const a = PLACEMENT_ASSESSMENT;
  out.push(
    "",
    "-- Placement activity (observations, not a test)",
    `insert into public.assessments (slug, title_vi, intro_vi, purpose, status)`,
    `values (${lit(a.slug)}, ${lit(a.title)}, ${lit(a.intro)}, 'placement', 'published')`,
    `on conflict (slug) do update set title_vi = excluded.title_vi, intro_vi = excluded.intro_vi;`,
  );
  a.questionSlugs.forEach((q, i) => {
    out.push(
      `insert into public.assessment_items (assessment_id, question_id, position)`,
      `values ((select id from public.assessments where slug = ${lit(a.slug)}), (select id from public.questions where slug = ${lit(q)}), ${num(i + 1)})`,
      `on conflict (assessment_id, position) do update set question_id = excluded.question_id;`,
    );
  });

  const slugs = (xs: string[]) => xs.map(lit).join(", ");
  const questionSlugs = sources.flatMap((w) =>
    w.skills.flatMap((s) =>
      s.lessons.flatMap((l) => l.questions.map((q) => q.id)),
    ),
  );
  out.push(
    "",
    "-- Verify: every seeded question has a consistent private key; counts match the source.",
    "do $$",
    "declare",
    "  v_bad text;",
    "begin",
    `  select string_agg(q.slug || ':' || private.question_key_problem(q.id), ', ') into v_bad`,
    `  from public.questions q where q.slug in (${slugs(questionSlugs)})`,
    `    and private.question_key_problem(q.id) is not null;`,
    "  if v_bad is not null then",
    "    raise exception 'seed: inconsistent answer keys: %', v_bad;",
    "  end if;",
    `  if (select count(*) from public.modules where slug in (${slugs(sources.map((w) => w.id))})) <> ${stats.modules}`,
    `    or (select count(*) from public.questions where slug in (${slugs(questionSlugs)})) <> ${stats.questions}`,
    `    or (select count(*) from private.question_answer_keys k join public.questions q on q.id = k.question_id where q.slug in (${slugs(questionSlugs)})) <> ${stats.keys}`,
    "  then",
    "    raise exception 'seed: unexpected row counts';",
    "  end if;",
    "end;",
    "$$;",
    "",
    "commit;",
    "",
  );
  return out.join("\n");
}
